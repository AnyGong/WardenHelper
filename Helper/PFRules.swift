import Foundation
import Darwin

/// Drops outgoing traffic to the listed networks with a pf anchor. macOS's stock
/// /etc/pf.conf already evaluates `com.apple/*`, so the anchor is loaded on its own and the
/// system file stays untouched. pf is enabled with a reference token (`pfctl -E`) and the
/// token is released again on disarm, so a pf that was already on stays on.
final class PFRules {

    private static let anchor = "com.apple/250.WardenHelper"
    private static let pfctl = "/sbin/pfctl"
    private static var tokenPath: String { BlockIPC.stateDirectory + "/pf-token" }
    private static var rulesPath: String { BlockIPC.stateDirectory + "/pf-rules.conf" }

    /// More new networks than this and ALL states are flushed in one go instead of the states of
    /// each new network being cut one by one. Cutting one by one is what keeps unrelated
    /// connections (SSH, downloads) alive, so the limit is high: domain rules resolve to many
    /// addresses, and a re-arm has to cut every connection opened while blocking was off.
    private static let perNetworkStateLimit = 512

    private var enabledThisRun = false
    private var loaded = Set<String>()

    // MARK: Arm

    /// Loads the anchor with `cidrs` (canonical text from the validator). An empty list removes it.
    func apply(cidrs: [String]) -> Bool {
        guard !cidrs.isEmpty else { return remove() }
        let wanted = Set(cidrs)

        // Unchanged and still in place: nothing to do.
        if enabledThisRun, wanted == loaded, anchorHasRules() { return true }

        let v4 = cidrs.filter { !$0.contains(":") }
        let v6 = cidrs.filter { $0.contains(":") }
        var text = "# generated by warden-helper-daemon\n"
        if !v4.isEmpty {
            text += "table <warden_helper_block4> const { \(v4.joined(separator: ", ")) }\n"
            text += "block return out quick inet to <warden_helper_block4>\n"
        }
        if !v6.isEmpty {
            text += "table <warden_helper_block6> const { \(v6.joined(separator: ", ")) }\n"
            text += "block return out quick inet6 to <warden_helper_block6>\n"
        }
        guard HelperFiles.write(text, to: Self.rulesPath) else { return false }
        guard ensureEnabled() else { return false }

        let load = Exec.run(Self.pfctl, ["-a", Self.anchor, "-f", Self.rulesPath])
        guard load.ok else {
            helperLog("block-pf load failed: \(Self.oneLine(load.output))")
            return false
        }
        // The rules are in force from here on; connections that are already open are cut next,
        // and only then is the anchor read back (the check must not delay the blocking).
        let fresh = wanted.subtracting(loaded)
        clearStates(fresh)
        guard anchorHasRules() else {
            helperLog("block-pf loaded but the anchor reads back empty")
            return false
        }
        loaded = wanted
        helperLog("block-pf loaded \(cidrs.count) network(s)")
        return true
    }

    private func anchorHasRules() -> Bool {
        let r = Exec.run(Self.pfctl, ["-a", Self.anchor, "-sr"])
        return r.ok && r.output.contains("block")
    }

    private func ensureEnabled() -> Bool {
        if enabledThisRun { return true }
        let old = HelperFiles.read(Self.tokenPath)?.trimmingCharacters(in: .whitespacesAndNewlines)
        let r = Exec.run(Self.pfctl, ["-E"])
        guard r.ok else {
            helperLog("block-pf enable failed: \(Self.oneLine(r.output))")
            return false
        }
        if let token = Self.parseToken(r.output) {
            HelperFiles.write(token, to: Self.tokenPath)
            // The token of a previous run (crash, update) is released only after the new one is held.
            if let old, !old.isEmpty, old != token { Exec.run(Self.pfctl, ["-X", old]) }
        } else {
            helperLog("block-pf: pfctl gave no token; pf will not be released on disarm")
        }
        enabledThisRun = true
        return true
    }

    /// `pfctl -E` prints `pf enabled` and `Token : 1234567890`.
    private static func parseToken(_ output: String) -> String? {
        for line in output.split(separator: "\n") where line.contains("Token") {
            guard let colon = line.firstIndex(of: ":") else { continue }
            let value = line[line.index(after: colon)...].trimmingCharacters(in: .whitespaces)
            if !value.isEmpty, value.allSatisfy({ $0.isASCII && $0.isNumber }) { return value }
        }
        return nil
    }

    /// Existing connections keep their pf state and would go on working: clear them.
    private func clearStates(_ networks: Set<String>) {
        guard !networks.isEmpty else { return }
        if networks.count > Self.perNetworkStateLimit {
            Exec.run(Self.pfctl, ["-F", "states"])
            return
        }
        let sorted = networks.sorted()
        DispatchQueue.concurrentPerform(iterations: sorted.count) { i in
            let network = sorted[i]
            let any = network.contains(":") ? "::/0" : "0.0.0.0/0"
            Exec.run(Self.pfctl, ["-k", any, "-k", network])
        }
    }

    // MARK: Disarm

    /// Flushes the anchor and releases the pf token. Also used by `--restore`, which is why it
    /// looks at the files on disk and not only at what this process did.
    @discardableResult
    func remove() -> Bool {
        let leftovers = HelperFiles.exists(Self.rulesPath) || HelperFiles.exists(Self.tokenPath)
        guard enabledThisRun || !loaded.isEmpty || leftovers else { return true }

        let rules = Exec.run(Self.pfctl, ["-a", Self.anchor, "-F", "rules"])
        let tables = Exec.run(Self.pfctl, ["-a", Self.anchor, "-F", "Tables"])
        guard rules.ok, tables.ok else {
            helperLog("block-pf flush failed: \(Self.oneLine(rules.output + tables.output))")
            return false                                    // keep the files; the next try repeats it
        }
        if let token = HelperFiles.read(Self.tokenPath)?.trimmingCharacters(in: .whitespacesAndNewlines),
           !token.isEmpty {
            let released = Exec.run(Self.pfctl, ["-X", token])
            if !released.ok { helperLog("block-pf release: \(Self.oneLine(released.output))") }
        }
        HelperFiles.remove(Self.tokenPath)
        HelperFiles.remove(Self.rulesPath)
        loaded = []
        enabledThisRun = false
        helperLog("block-pf removed")
        return true
    }

    private static func oneLine(_ text: String) -> String {
        String(text.split(separator: "\n").joined(separator: " ").prefix(200))
    }
}
